"""Scan the ELK Java sources we port and derive the Lisp names (PORTING.md).

Writes:
  src/runtime/jcalls.lisp   call macros for every method/static/constructor
  tools/classnames.tsv      java.fq.Name -> lisp-class-name
"""
import os, re, sys, collections

ROOT = '/tmp/elk-src/elk'
PLUGINS = ['org.eclipse.elk.graph', 'org.eclipse.elk.graph.json', 'org.eclipse.elk.core',
           'org.eclipse.elk.alg.common', 'org.eclipse.elk.alg.layered', 'org.eclipse.elk.alg.force',
           'org.eclipse.elk.alg.mrtree', 'org.eclipse.elk.alg.radial', 'org.eclipse.elk.alg.disco',
           'org.eclipse.elk.alg.spore', 'org.eclipse.elk.alg.rectpacking', 'org.eclipse.elk.alg.topdownpacking']
TESTS = [d for d in os.listdir(ROOT + '/test') if d.endswith('.test')]

def kebab(name):
    if re.fullmatch(r'[A-Z0-9_]+', name):
        return name.replace('_', '-').lower()
    out = []
    for i, c in enumerate(name):
        prev = name[i-1] if i else ''
        nxt = name[i+1] if i + 1 < len(name) else ''
        if c == '_':
            out.append('-'); continue
        if i and c.isupper() and (prev.islower() or prev.isdigit() or (prev.isupper() and nxt.islower())):
            out.append('-')
        out.append(c)
    return ''.join(out).lower()

CL_SYMBOLS = set(open('tools/cl-symbols.txt').read().split())

def method_name(m):
    k = kebab(m)
    return 'j-' + k if k in CL_SYMBOLS else k

files = []
for p in PLUGINS:
    for d, _, fs in os.walk(f'{ROOT}/plugins/{p}/src'):
        files += [os.path.join(d, f) for f in fs if f.endswith('.java')]
for t in TESTS:
    for d, _, fs in os.walk(f'{ROOT}/test/{t}/src'):
        files += [os.path.join(d, f) for f in fs if f.endswith('.java')]

# Classes (top level + nested) by fully qualified name.
classes = {}
decl = re.compile(r'\b(class|interface|enum)\s+([A-Z]\w*)')
for f in files:
    src = open(f, encoding='utf-8', errors='replace').read()
    pkg = re.search(r'^package\s+([\w.]+);', src, re.M).group(1)
    for m in decl.finditer(src):
        classes.setdefault(m.group(2), set()).add(pkg)

def plugin_of(pkg):
    parts = pkg.split('.')
    # org.eclipse.elk.alg.layered.p3order -> layered ; org.eclipse.elk.core.util -> core
    if parts[3] == 'alg':
        return parts[4], parts[5:]
    return parts[3], parts[4:]

names = {}
for simple, pkgs in classes.items():
    k = kebab(simple)
    if len(pkgs) == 1:
        names[(simple, next(iter(pkgs)))] = k
        continue
    # duplicate: prefix with plugin, then with the deepest differing subpackage
    by_plugin = collections.defaultdict(list)
    for pkg in pkgs:
        by_plugin[plugin_of(pkg)[0]].append(pkg)
    for plug, plist in by_plugin.items():
        for pkg in plist:
            if len(plist) == 1:
                names[(simple, pkg)] = f'{plug}-{k}'
            else:
                sub = plugin_of(pkg)[1]
                names[(simple, pkg)] = f'{plug}-{"-".join(sub[-1:])}-{k}' if sub else f'{plug}-{k}'

with open('tools/classnames.tsv', 'w') as out:
    for (simple, pkg), lisp in sorted(names.items(), key=lambda x: (x[0][1], x[0][0])):
        out.write(f'{pkg}.{simple}\t{lisp}\n')

# Methods: instance vs static, per declaring class (approximate parse).
meth = re.compile(r'^\s*((?:public|protected|private|static|final|abstract|synchronized|default|native|\s)*)'
                  r'(?:<[^>]+>\s+)?[\w<>\[\],.? ]+?\s+([a-z]\w*)\s*\(', re.M)
instance, static = set(), set()
ctor_classes = set()
for f in files:
    src = open(f, encoding='utf-8', errors='replace').read()
    pkg = re.search(r'^package\s+([\w.]+);', src, re.M).group(1)
    top = os.path.basename(f)[:-5]
    for m in meth.finditer(src):
        mods, name = m.group(1), m.group(2)
        if name in ('if', 'for', 'while', 'switch', 'return', 'new', 'catch', 'synchronized', 'else'):
            continue
        if 'static' in mods:
            static.add((names.get((top, pkg), kebab(top)), kebab(name)))
        else:
            instance.add(method_name(name))
    for c in classes:
        if (c, pkg) in names:
            ctor_classes.add(names[(c, pkg)])

with open('src/runtime/jcalls.lisp', 'w') as out:
    out.write(';;;; jcalls.lisp -- GENERATED by tools/javanames.py.  Call macros for every\n')
    out.write(';;;; Java method, static method and constructor name in the ported sources.\n\n')
    out.write('(in-package #:elk)\n\n(define-jcalls :instance\n')
    for n in sorted(instance):
        out.write(f'  {n}\n')
    out.write(')\n\n(define-jcalls :static\n')
    for c, n in sorted(static):
        out.write(f'  {c}.{n}\n')
    for c in sorted(ctor_classes):
        out.write(f'  new-{c}\n')
    out.write(')\n')
print(len(files), 'files', len(names), 'classes', len(instance), 'instance names', len(static), 'statics')
