"""Generate the Lisp side of ELK's metadata from the Java and .melk sources.

  src/gen-enums/enums.lisp    every enum constant in the ported packages (DEFJENUM)
  src/gen-options/options.lisp  every layout option (CoreOptions, LayeredOptions, ...),
                        algorithm descriptions and option support, mirroring
                        what ELK's MetaDataJvmModelInferrer generates in Java

Naming follows PORTING.md and tools/classnames.tsv.
"""
import os, re, sys

ROOT = '/tmp/elk-src/elk'
PLUGINS = ['graph', 'graph.json', 'core', 'alg.common', 'alg.layered', 'alg.force', 'alg.mrtree',
           'alg.radial', 'alg.disco', 'alg.spore', 'alg.rectpacking', 'alg.topdownpacking']
sys.path.insert(0, os.path.dirname(__file__))

def kebab(name):
    if re.fullmatch(r'[A-Z0-9_]+', name):
        return name.replace('_', '-').lower()
    out = []
    for i, c in enumerate(name):
        prev = name[i-1] if i else ''
        nxt = name[i+1] if i + 1 < len(name) else ''
        if c == '_':
            out.append('-'); continue
        if i and c.isupper() and (prev.islower() or prev.isdigit() or (prev.isupper() and nxt.islower())):
            out.append('-')
        out.append(c)
    return ''.join(out).lower()

CLASSNAMES = {}
SIMPLE = {}
for line in open('tools/classnames.tsv'):
    fq, lisp = line.rstrip('\n').split('\t')
    CLASSNAMES[fq] = lisp
    SIMPLE.setdefault(fq.rsplit('.', 1)[1], []).append(fq)

def strip_comments(s):
    return re.sub(r'/\*.*?\*/|//[^\n]*', lambda m: '' if m.group(0).startswith('//') else ' ' * 0, s, flags=re.S)

# ---------------------------------------------------------------- enums

ENUMS = {}   # fq -> (lisp, [constants])
def scan_enums():
    for p in PLUGINS:
        for d, _, fs in os.walk(f'{ROOT}/plugins/org.eclipse.elk.{p}/src'):
            for f in fs:
                if not f.endswith('.java'):
                    continue
                src = strip_comments(open(os.path.join(d, f), errors='replace').read())
                pkg = re.search(r'^\s*package\s+([\w.]+);', src, re.M).group(1)
                for m in re.finditer(r'\benum\s+(\w+)[^{]*\{', src):
                    name = m.group(1)
                    body = src[m.end():]
                    # constants run up to the first ';' or '}' at depth 0
                    depth, i, consts, cur = 0, 0, [], ''
                    while i < len(body):
                        c = body[i]
                        if c in '({':
                            depth += 1
                        elif c in ')}':
                            if depth == 0:
                                break
                            depth -= 1
                        elif c == ';' and depth == 0:
                            break
                        elif c == ',' and depth == 0:
                            consts.append(cur); cur = ''; i += 1; continue
                        if depth == 0 or c not in '':
                            cur += c
                        i += 1
                    consts.append(cur)
                    names = []
                    for c in consts:
                        c = re.sub(r'@\w+(\([^)]*\))?', '', c).strip()
                        mm = re.match(r'([A-Z_][A-Z0-9_]*)', c)
                        if mm:
                            names.append(mm.group(1))
                    fq = f'{pkg}.{name}'
                    lisp = CLASSNAMES.get(fq) or kebab(name)
                    ENUMS[fq] = (lisp, names)

scan_enums()
ENUM_BY_SIMPLE = {}
for fq, (lisp, consts) in ENUMS.items():
    ENUM_BY_SIMPLE.setdefault(fq.rsplit('.', 1)[1], []).append(fq)


with open('src/gen-enums/enums.lisp', 'w') as out:
    out.write(';;;; enums.lisp -- GENERATED by tools/genmeta.py: the constants of every\n')
    out.write(';;;; enum in the ported ELK packages.  Methods and constructor-argument\n')
    out.write(';;;; fields are ported by hand next to the code that owns the enum.\n\n')
    out.write('(in-package #:elk)\n\n')
    for fq in sorted(ENUMS):
        lisp, consts = ENUMS[fq]
        out.write(f';; {fq}\n(defjenum {lisp} ({" ".join(kebab(c) for c in consts)}))\n\n')

# ---------------------------------------------------------------- melk

TOKEN = re.compile(r'"(?:\\.|[^"\\])*"|\^?[A-Za-z_][\w]*(?:\.\^?[A-Za-z_][\w]*)*|-?\d+(?:\.\d+)?[fFdD]?|==|[{}()=,:<>;\[\]]|\S')

class Melk:
    def __init__(self, path):
        self.path = path
        raw = open(path).read()
        # One pass over the whole text: strings (possibly multi-line), comments, tokens.
        self.toks = []
        self.lines = raw.split('\n')
        pat = re.compile(r'"(?:\\.|[^"\\])*"|/\*.*?\*/|//[^\n]*|\^?[A-Za-z_][\w]*(?:\.\^?[A-Za-z_][\w]*)*|-?\d+(?:\.\d+)?[fFdD]?|==|[{}()=,:<>;\[\]]|\S', re.S)
        line_starts = [0]
        for l in self.lines:
            line_starts.append(line_starts[-1] + len(l) + 1)
        import bisect
        for m in pat.finditer(raw):
            t = m.group(0)
            if t.startswith('//') or t.startswith('/*'):
                continue
            ln = bisect.bisect_right(line_starts, m.start()) - 1
            self.toks.append((t, ln, m.start() - line_starts[ln] + len(t)))
        self.i = 0
        self.imports = {}
        self.package = None
        self.bundle = {}
        self.options = []      # dicts
        self.algorithms = []

    def peek(self, k=0):
        return self.toks[self.i + k][0] if self.i + k < len(self.toks) else None
    def next(self):
        t = self.toks[self.i]; self.i += 1; return t[0]
    def rest_of_line(self):
        """Raw text from the current token to the end of its line; consume it."""
        tok, ln, end = self.toks[self.i]
        start = end - len(tok)
        text = self.lines[ln][start:].strip()
        while self.i < len(self.toks) and self.toks[self.i][1] == ln:
            self.i += 1
        return text
    def string(self):
        t = self.next()
        while self.peek() and self.peek().startswith('"'):
            self.next()
        return t

    def parse(self):
        groups = []
        while self.i < len(self.toks):
            t = self.next()
            if t == 'package':
                self.package = self.next()
            elif t == 'import':
                q = self.next().replace('^', '')
                self.imports[q.rsplit('.', 1)[1]] = q
            elif t == 'bundle':
                self.parse_block(self.bundle)
            elif t == 'category':
                self.next(); self.skip_block()
            elif t == 'algorithm':
                self.parse_algorithm()
            elif t == 'group':
                groups.append(self.next().replace('^', '')); self.expect('{')
            elif t in ('advanced', 'programmatic', 'output', 'global', 'experimental', 'deprecated', 'option'):
                mods = [t]
                while t != 'option':
                    t = self.next(); mods.append(t)
                self.parse_option(groups, mods)
            elif t == '}':
                groups.pop()
            else:
                raise SyntaxError(f'{self.path}: unexpected {t}')
        return self

    def expect(self, t):
        got = self.next()
        if got != t:
            raise SyntaxError(f'{self.path}: expected {t} got {got}')

    def skip_block(self):
        self.expect('{'); depth = 1
        while depth:
            t = self.next()
            depth += {'{': 1, '}': -1}.get(t, 0)

    def parse_block(self, d):
        self.expect('{')
        while self.peek() != '}':
            k = self.next(); d[k] = self.next()
        self.next()

    def parse_option(self, groups, mods):
        name = self.next().replace('^', '')
        self.expect(':')
        typ = self.rest_type()
        opt = {'name': name, 'groups': list(groups), 'type': typ, 'mods': mods, 'targets': [],
               'legacy': [], 'default': None, 'lower': None, 'upper': None}
        if self.peek() == '{':
            self.next()
            while self.peek() != '}':
                k = self.next()
                if k in ('label', 'description', 'documentation'):
                    self.string()
                elif k in ('default', 'lowerBound', 'upperBound'):
                    self.expect('=')
                    opt[{'default': 'default', 'lowerBound': 'lower', 'upperBound': 'upper'}[k]] = self.rest_of_line()
                elif k == 'targets':
                    opt['targets'].append(self.next())
                    while self.peek() == ',':
                        self.next(); opt['targets'].append(self.next())
                elif k == 'legacyIds':
                    opt['legacy'].append(self.next())
                    while self.peek() == ',':
                        self.next(); opt['legacy'].append(self.next())
                elif k == 'requires':
                    self.rest_of_line()
                else:
                    raise SyntaxError(f'{self.path}: option key {k}')
            self.next()
        self.options.append(opt)

    def rest_type(self):
        t = self.next()
        if self.peek() == '<':
            depth = 0
            while True:
                x = self.next(); t += x
                depth += {'<': 1, '>': -1}.get(x, 0)
                if depth == 0:
                    break
        return t

    def parse_algorithm(self):
        name = self.next().replace('^', '')
        self.expect('('); provider = self.next(); self.expect(')')
        alg = {'name': name, 'provider': provider, 'supports': [], 'category': None, 'features': [],
               'metadataClass': None, 'label': None}
        self.expect('{')
        while self.peek() != '}':
            k = self.next()
            if k in ('label',):
                alg['label'] = self.string()
            elif k in ('description', 'documentation'):
                self.string()
            elif k == 'metadataClass':
                alg['metadataClass'] = self.next()
            elif k == 'category':
                alg['category'] = self.next()
            elif k == 'preview':
                self.rest_of_line()
            elif k == 'features':
                alg['features'].append(self.next())
                while self.peek() == ',':
                    self.next(); alg['features'].append(self.next())
            elif k == 'validator':
                self.next()
            elif k == 'supports':
                ref = self.next().replace('^', '')
                default = None
                if self.peek() == '=':
                    self.next()
                    default = self.rest_of_line()
                alg['supports'].append((ref, default))
            else:
                raise SyntaxError(f'{self.path}: algorithm key {k}')
        self.next()
        self.algorithms.append(alg)

MELKS = []
for p in PLUGINS:
    for d, _, fs in os.walk(f'{ROOT}/plugins/org.eclipse.elk.{p}/src'):
        for f in fs:
            if f.endswith('.melk'):
                MELKS.append(Melk(os.path.join(d, f)).parse())

def qualified_name(prefix, member, groups):
    prefix = prefix.replace('^', '')
    if member == prefix.rsplit('.', 1)[-1]:
        prefix = prefix.rsplit('.', 1)[0]
    return prefix + ('.' if groups else '') + '.'.join(groups) + '.' + member

def upper_us(s):
    return ''.join(('_' + c if c.isupper() and i > 0 else c.upper()) for i, c in enumerate(s))

def constant_name(opt):
    parts = [upper_us(g) for g in opt['groups']] + [upper_us(opt['name'])]
    return '_'.join(parts)

def resolve_class(simple, melk):
    """Java simple/qualified class name in a melk -> fully qualified."""
    simple = simple.replace('^', '')
    head = simple.split('.')[0]
    if head in melk.imports:
        base = melk.imports[head]
        return base + simple[len(head):]
    if '.' in simple and simple.split('.')[0][0].islower():
        return simple
    for pkg in (melk.package + '.options', melk.package, 'org.eclipse.elk.core.options'):
        fq = f'{pkg}.{simple}'
        if fq in CLASSNAMES or fq in ENUMS:
            return fq
    cands = SIMPLE.get(simple.split('.')[-1], [])
    if len(cands) == 1:
        return cands[0]
    return None

def lisp_class(fq):
    if fq is None:
        return None
    if fq in CLASSNAMES:
        return CLASSNAMES[fq]
    # nested class: a.b.Outer.Inner
    return CLASSNAMES.get(fq.rsplit('.', 1)[0][:0] + fq) or kebab(fq.rsplit('.', 1)[1])

UNKNOWN = set()

def lisp_type(typ, melk):
    t = typ.replace('^', '')
    if t in ('double', 'float', 'Double', 'Float'):
        return ':double'
    if t in ('int', 'Integer', 'long'):
        return ':int'
    if t in ('boolean', 'Boolean'):
        return ':boolean'
    if t == 'String':
        return ':string'
    m = re.fullmatch(r'EnumSet<(.+)>', t)
    if m:
        fq = resolve_class(m.group(1), melk)
        return f'(:enum-set {ENUMS[fq][0] if fq in ENUMS else kebab(m.group(1))})'
    m = re.fullmatch(r'List<(.+)>', t)
    if m:
        return f'(:list "{m.group(1)}")'
    fq = resolve_class(t, melk)
    if fq and fq not in ENUMS:
        parts = fq.split('.')
        fq = '.'.join([x for x in parts[:-1] if x[0].islower()] + parts[-1:])
    if fq in ENUMS:
        return f'(:enum {ENUMS[fq][0]})'
    if fq is None:
        fq2 = resolve_nested(t, melk)
        if fq2 in ENUMS:
            return f'(:enum {ENUMS[fq2][0]})'
    return f'(:object "{t}")'

def resolve_nested(dotted, melk):
    parts = dotted.split('.')
    for i in range(len(parts), 0, -1):
        outer = resolve_class('.'.join(parts[:i]), melk)
        if outer:
            fq = outer + ('.' + '.'.join(parts[i:]) if parts[i:] else '')
            # nested enums are scanned with their outer package only
            simple = fq.rsplit('.', 1)[1]
            for e in ENUM_BY_SIMPLE.get(simple, []):
                if fq.startswith(e.rsplit('.', 1)[0]):
                    return e
            return fq
    return None

def split_args(s):
    out, depth, cur = [], 0, ''
    for c in s:
        if c in '([': depth += 1
        if c in ')]': depth -= 1
        if c == ',' and depth == 0:
            out.append(cur.strip()); cur = ''
        else:
            cur += c
    if cur.strip():
        out.append(cur.strip())
    return out

def expr(e, melk):
    e = e.strip()
    if e in ('true',):
        return 't'
    if e in ('false', 'null'):
        return 'nil'
    if re.fullmatch(r'-?\d+', e):
        return e
    m = re.fullmatch(r'(-?\d*\.?\d+(?:[eE][-+]?\d+)?)[fFdD]?', e)
    if m:
        v = m.group(1)
        return (v if '.' in v or 'e' in v.lower() else v + '.0') + 'd0' if 'e' not in v.lower() else v.replace('e', 'd').replace('E', 'd')
    m = re.fullmatch(r'"(.*)"', e)
    if m:
        return e
    m = re.fullmatch(r'#\[(.*)\]', e)
    if m:
        return f'(jlist {" ".join(expr(a, melk) for a in split_args(m.group(1)))})'
    m = re.fullmatch(r'([A-Z]\w*)\.([a-z]\w*)', e)
    if m:
        return expr(e + '()', melk)
    if e == 'Integer.MAX_VALUE':
        return 'integer.max-value'
    m = re.fullmatch(r'new\s+([\w.]+)\s*\((.*)\)', e)
    if m:
        cls = lisp_class(resolve_class(m.group(1), melk)) or kebab(m.group(1))
        args = [expr(a, melk) for a in split_args(m.group(2))]
        return f'(new-{cls}{"".join(" " + a for a in args)})'
    m = re.fullmatch(r'EnumSet\.noneOf\(([\w.]+)(?:\.class)?\)', e)
    if m:
        fq = resolve_class(m.group(1), melk)
        return f"(enum-set.none-of '{ENUMS[fq][0]})"
    m = re.fullmatch(r'EnumSet\.of\((.*)\)', e)
    if m:
        return f'(enum-set.of {" ".join(expr(a, melk) for a in split_args(m.group(1)))})'
    m = re.fullmatch(r'([\w.]+)\.(\w+)\((.*)\)', e)
    if m:
        fq = resolve_class(m.group(1), melk) or resolve_nested(m.group(1), melk)
        cls = (ENUMS[fq][0] if fq in ENUMS else lisp_class(fq)) or kebab(m.group(1))
        args = [expr(a, melk) for a in split_args(m.group(3))]
        return f'({cls}.{kebab(m.group(2))}{"".join(" " + a for a in args)})'
    m = re.fullmatch(r'([\w.]+)\.([A-Z_0-9]+)', e)
    if m:
        fq = resolve_class(m.group(1), melk) or resolve_nested(m.group(1), melk)
        if fq in ENUMS:
            return f'{ENUMS[fq][0]}.{kebab(m.group(2))}'
        return f'{lisp_class(fq) or kebab(m.group(1))}.{kebab(m.group(2))}'
    UNKNOWN.add(e)
    return f'(error "untranslated default: {e}")'

# Options by fully qualified id, with the melk that declared them.
ALL = {}
for mk in MELKS:
    prefix = mk.bundle.get('idPrefix', mk.package).replace('^', '')
    holder = kebab(mk.bundle['metadataClass'].split('.')[-1])
    mk.holder = holder
    mk.prefix = prefix
    for o in mk.options:
        o['id'] = qualified_name(prefix, o['name'], o['groups'])
        o['const'] = kebab(constant_name(o))
        o['melk'] = mk
        o['holder'] = holder
        ALL[o['id']] = o
        ALL.setdefault(mk.package + '.' + '.'.join(o['groups'] + [o['name']]), o)

def find_option(ref, mk):
    if ref in ALL:
        return ALL[ref]
    for cand in (mk.prefix + '.' + ref, 'org.eclipse.elk.' + ref):
        if cand in ALL:
            return ALL[cand]
    # legacy alg.layered prefix
    if ref.startswith('org.eclipse.elk.alg.layered.'):
        return find_option(ref.replace('org.eclipse.elk.alg.layered.', 'org.eclipse.elk.layered.'), mk)
    raise KeyError(f'{mk.path}: unknown option {ref}')

with open('src/gen-options/options.lisp', 'w') as out:
    w = out.write
    w(';;;; options.lisp -- GENERATED by tools/genmeta.py from the .melk files:\n')
    w(';;;; the layout options (CoreOptions, LayeredMetaDataProvider, ...), the\n')
    w(';;;; per-algorithm option holders (LayeredOptions, ...) with their defaults,\n')
    w(';;;; and the algorithm registry.  See src/core/data.lisp for the registry API.\n\n')
    w('(in-package #:elk)\n\n')
    for mk in MELKS:
        w(f';;; ---- {os.path.relpath(mk.path, ROOT)}\n\n')
        for o in mk.options:
            vis = 'hidden' if set(o['mods']) & {'programmatic', 'output', 'global'} else ('advanced' if 'advanced' in o['mods'] else 'visible')
            w(f'(define-layout-option {o["holder"]}.{o["const"]} "{o["id"]}"\n')
            w(f'  :type {lisp_type(o["type"], mk)}\n')
            if o['default'] is not None:
                w(f'  :default {expr(o["default"], mk)}\n')
            if o['lower'] is not None:
                w(f'  :lower {expr(o["lower"], mk)}\n')
            if o['upper'] is not None:
                w(f'  :upper {expr(o["upper"], mk)}\n')
            w(f'  :targets ({" ".join(":" + t for t in o["targets"])})\n')
            if o['legacy']:
                w(f'  :legacy-ids ({" ".join(chr(34) + x + chr(34) for x in o["legacy"])})\n')
            w(f'  :visibility :{vis})\n\n')
        for a in mk.algorithms:
            aid = qualified_name(mk.prefix, a['name'], [])
            aholder = kebab(a['metadataClass'].split('.')[-1]) if a['metadataClass'] else mk.holder
            provider = lisp_class(resolve_class(a['provider'], mk)) or kebab(a['provider'])
            w(f'(defparameter {aholder}.algorithm-id "{aid}")\n')
            for ref, default in a['supports']:
                o = find_option(ref, mk)
                src = f'{o["holder"]}.{o["const"]}'
                if default is None:
                    w(f'(define-algorithm-option {aholder}.{o["const"]} {src})\n')
                else:
                    w(f'(define-algorithm-option {aholder}.{o["const"]} {src} {expr(default, mk)})\n')
            cat = a['category']
            if cat and '.' not in cat:
                cat = qualified_name(mk.prefix, cat, [])
            w(f'(register-layout-algorithm "{aid}"\n')
            w(f"  :name {a['label'] or chr(34) + a['name'] + chr(34)} :provider '{provider}\n")
            w(f'  :category {chr(34) + cat + chr(34) if cat else "nil"} :bundle {mk.bundle.get("label", "nil")}\n')
            w(f'  :features (list {" ".join("graph-feature." + kebab(f) for f in a["features"])})\n')
            w(f'  :supports (list\n')
            for ref, default in a['supports']:
                o = find_option(ref, mk)
                w(f'    (cons "{o["id"]}" {aholder}.{o["const"]})\n')
            w('  ))\n\n')

